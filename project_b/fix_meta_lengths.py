def main() -> int:
    changed = 0
    for p in ROOT.glob("*.html"):
        if p.name in ("404.html",):
            continue
        s = p.read_text(encoding="utf-8", errors="ignore")
        m = T_DESC.search(s)
        if not m:
            continue
        desc = CUSTOM.get(p.name, m.group(2).strip())
        if len(desc) < 150 and SUFFIX not in desc:
            desc = desc + SUFFIX
        if len(desc) < 150:
            desc = desc + SUFFIX2
        extra = "含音域、现场、作品、问答与研究索引，数据附来源与口径。"
        while len(desc) < 150:
            desc = desc + extra
        if desc != m.group(2):
            s = s[:m.start(2)] + desc + s[m.end(2):]
            p.write_text(s, encoding="utf-8")
            changed += 1
    print("更新", changed, "页 description")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
